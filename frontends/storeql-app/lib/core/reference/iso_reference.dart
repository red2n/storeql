/// The name of the country [code] names (`FR` → *France*); a code this list
/// does not know yet stays as it came.
String countryName(String code) =>
    isoCountries[code.trim().toUpperCase()]?.$1 ?? code;

/// The country a code names, as it reads after "in": *the United Kingdom*,
/// *France*. A code this list does not know yet stays as it came.
String countryInSentence(String code) {
  final name = isoCountries[code.trim().toUpperCase()]?.$1;
  if (name == null) return code;
  return _takesThe(name) ? 'the $name' : name;
}

/// The names English writes with "the": a plural or a union of parts (the
/// Netherlands, the Cayman Islands, the United States), a republic or a
/// territory named for what it is, and a few by custom (the Gambia).
bool _takesThe(String name) {
  const byName = {
    'Bahamas',
    'Comoros',
    'Congo',
    'Congo (Democratic Republic)',
    'Gambia',
    'Holy See (Vatican City)',
    'Isle of Man',
    'Maldives',
    'Netherlands',
    'Philippines',
    'Seychelles',
  };
  if (byName.contains(name)) return true;
  if (name.startsWith('United ')) return true;
  if (name.startsWith('Virgin Islands')) return true;
  return name.endsWith(' Islands') ||
      name.endsWith(' Republic') ||
      name.endsWith(' Territory') ||
      name.endsWith(' Territories');
}

/// Whether [code] names a country: exactly one of [isoCountries], however it
/// is cased or spaced.
///
/// Exact, because the list is the services' own set (tenant-svc and every
/// `TenantProfiles` caller check against the JDK's `Locale.getISOCountries`):
/// a code it does not carry — reserved or user-assigned (UK, EU, XK), withdrawn
/// (YU), or merely of the right shape (JX) — is one the services answer
/// `COUNTRY_INVALID` to, so a form shows it as needing a country rather than
/// keep it and fail on save.
bool isCountryCode(String code) =>
    isoCountries.containsKey(code.trim().toUpperCase());

